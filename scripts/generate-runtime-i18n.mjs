import { writeFile } from "node:fs/promises";
import { createServer } from "vite";

function formalizeItalian(value) {
  const phrases = [
    [/\bRaccontaci\b/g, "Ci racconti"],
    [/\bScrivici\b/g, "Ci scriva"],
    [/\bAffida\b/g, "Affidi"],
    [/\bScopri\b/g, "Scopra"],
    [/\bDescrivi\b/g, "Descriva"],
    [/\bIndica\b/g, "Indichi"],
    [/\bPresenta\b/g, "Presenti"],
    [/\bTrova\b/g, "Trovi"],
    [/\bSeleziona\b/g, "Selezioni"],
    [/\bMetti alla prova\b/g, "Verifichi"],
    [/\bDecidi tu\b/g, "Decide Lei"],
    [/\bDecidi\b/g, "Decida"],
    [/\bSai\b/g, "Sa"],
    [/\bPuoi\b/g, "Può"],
  ];
  let result = value;
  for (const [pattern, replacement] of phrases) result = result.replace(pattern, replacement);
  return result
    .replace(/\bcon te\b/gi, "con Lei")
    .replace(/\bti\b/gi, "La")
    .replace(/\btuo\b/gi, "Suo")
    .replace(/\btua\b/gi, "Sua")
    .replace(/\btuoi\b/gi, "Suoi")
    .replace(/\btue\b/gi, "Sue")
    .replace(/\bvostro\b/gi, "Suo")
    .replace(/\bvostra\b/gi, "Sua")
    .replace(/\bvostri\b/gi, "Suoi")
    .replace(/\bvostre\b/gi, "Sue")
    .replace(/\btu\b/gi, "Lei");
}

const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: "custom" });

try {
  const [core, supplemental, publicCopy, generated, reviewed, audit, quality, current, complete, finalReview] = await Promise.all([
    server.ssrLoadModule("/lib/i18n-source.ts"),
    server.ssrLoadModule("/lib/i18n-supplement.ts"),
    server.ssrLoadModule("/lib/i18n-public.ts"),
    server.ssrLoadModule("/lib/i18n-generated.ts"),
    server.ssrLoadModule("/lib/i18n-reviewed.ts"),
    server.ssrLoadModule("/lib/i18n-audit-fixes.ts"),
    server.ssrLoadModule("/lib/i18n-quality.ts"),
    server.ssrLoadModule("/lib/i18n-current.ts"),
    server.ssrLoadModule("/lib/i18n-audit-complete.ts"),
    server.ssrLoadModule("/lib/i18n-final-review.ts"),
  ]);

  const merged = {
    ...generated.generatedMessages,
    ...core.messages,
    ...supplemental.supplementalMessages,
    ...publicCopy.publicMessages,
    ...reviewed.reviewedMessages,
    ...audit.auditFixMessages,
    ...quality.qualityMessages,
    ...current.currentMessages,
    ...complete.auditCompleteMessages,
    ...finalReview.finalReviewMessages,
  };
  const runtime = Object.fromEntries(
    Object.entries(merged).map(([source, value]) => [source, { it: formalizeItalian(value.it), en: value.en }]),
  );
  const content = `// Generated by scripts/generate-runtime-i18n.mjs.\n` +
    `// Only the three public languages are shipped to visitors: FR keys, IT and EN values.\n` +
    `export const runtimeMessages: Record<string, { it: string; en: string }> = ${JSON.stringify(runtime)};\n`;
  await writeFile(new URL("../lib/i18n-runtime.ts", import.meta.url), content, "utf8");
} finally {
  await server.close();
}
